def bucket(top: str, inside: str) -> list[str]:
    """A bucket whose top row and inside hold something."""
    rows = list(BUCKET)
    rows[3] = '.#' + top * 8 + '#.'
    for y in (4, 5, 6, 7, 8):
        width = 8 if y < 6 else 6
        pad = 2 if y < 6 else 3
        rows[y] = rows[y][:pad] + inside * width + rows[y][pad + width:]
    return rows


