def bottle(fill: str, top: int = 6) -> list[str]:
    """A bottle filled with a colour from row `top` down."""
    rows = list(BOTTLE)
    for y in range(top, 9):
        rows[y] = '..#' + fill * 6 + '#..'
    return rows


